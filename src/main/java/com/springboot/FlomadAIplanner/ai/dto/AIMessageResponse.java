package com.springboot.FlomadAIplanner.ai.dto;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonPropertyDescription;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.util.List;

/**
 * Represents the response from the AI, including the main message and suggested next inputs.
 * The primary purpose of this response is to provide the user with actionable insights and
 * contextually relevant suggestions for continuing their interaction with the system.
 *
 * Suggestions should align with the user's current query and offer clear next steps or
 * potential exploration paths. These suggestions are designed to help guide the user
 * towards the next logical action, rather than asking further questions.
 */
@Data
@NoArgsConstructor
public class AIMessageResponse {

    @JsonPropertyDescription("The main response message generated by the AI based on the user's input.")
    @JsonProperty("text")
    private String text;

    /**
     * Actionable suggestions that guide the user towards the next logical step in the conversation.
     * These suggestions are designed to be predefined actions (not questions) that the user can take.
     * Example suggestions:
     * - "Browse top travel destinations"
     * - "Find popular travel itineraries"
     * - "Explore nature trips in your area"
     * - "View flight options for your destination"
     *
     * These suggestions aim to drive the conversation forward, providing clear, actionable steps.
     */
    @JsonPropertyDescription("A list of up to 4 predefined actionable responses that guide the user to take the next step in the conversation.")
    @JsonProperty("suggestions")
    private List<String> suggestions;

    /**
     * Constructor to initialize the AIMessageResponse with a main text response and suggestions.
     * @param text The main message from the AI.
     * @param suggestions The list of actionable suggestions.
     */
    public AIMessageResponse(String text, List<String> suggestions) {
        this.text = text;
        this.suggestions = suggestions;
    }
}





