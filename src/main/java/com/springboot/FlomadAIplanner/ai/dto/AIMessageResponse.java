package com.springboot.FlomadAIplanner.ai.dto;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonPropertyDescription;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.util.List;

/**
 * Represents the response from the AI, including the main message and suggested next inputs.
 * The primary purpose of this response is to provide the user with actionable insights and
 * contextually relevant suggestions for continuing their interaction with the system.
 *
 * Suggestions should align with the user's current query and offer clear next steps or
 * potential exploration paths. These suggestions are generated dynamically by the AI based
 * on the user's input and are designed to enhance the conversational flow.
 */
@Data
@AllArgsConstructor
@NoArgsConstructor
public class AIMessageResponse {

    /**
     * The main response message generated by the AI based on the user's input.
     * This message serves as the core response and provides the information or
     * solution requested by the user.
     *
     * Example: "Here are the top attractions in Paris: Eiffel Tower, Louvre Museum, and Montmartre."
     */

    @JsonPropertyDescription("The main text message generated by the AI based on the user's input.")
    @JsonProperty("text")
    private String text;

    /**
     * Suggestions for possible next steps or user inputs that can continue the conversation.
     * These suggestions are dynamically generated by the AI based on the context of the user's input
     * and the response provided. They aim to make the interaction seamless and guide the user
     * towards further exploration or actions.
     *
     * Example suggestions for a query about Paris attractions:
     * - "Find restaurants near the Eiffel Tower"
     * - "Check availability of tickets to the Louvre"
     * - "Explore more cities in France"
     *
     * These suggestions are context-aware and designed to keep the conversation engaging and helpful.
     */

    @JsonPropertyDescription("A list of up to 4 dynamically generated suggestions for the user's next inputs.")
    @JsonProperty("suggestions")
    private List<String> suggestions;

    /**
     * Constructor to initialize the AIMessageResponse with a main text response only.
     * If no suggestions are provided, this constructor ensures the suggestions field is initialized
     * to an empty list to prevent null pointer issues.
     *
     * @param text The main message from the AI.
     */
    public AIMessageResponse(String text) {
        this.text = text;
        this.suggestions = List.of(); // Default to empty list if no suggestions are provided

    }
}
